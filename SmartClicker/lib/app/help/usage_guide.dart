// Help: ideas of use — a neural network (or another program) and a script
// pass tasks to each other through files; running scripts from outside.

const String usageGuide = r'''
ИДЕИ ИСПОЛЬЗОВАНИЯ
==================

Скрипт может работать вместе с другой программой — например, с нейросетью,
которая умеет читать и менять файлы. Нейросеть пишет задание в файл, скрипт
его выполняет кликами и клавишами и отвечает в тот же файл.
Файл без пути лежит в папке files (Настройки → «Папка с данными» → files).

1. ЗАДАНИЕ ИЗ ФАЙЛА: ОТПРАВИТЬ ПРОМПТ В НУЖНОЕ ВРЕМЯ
---------------------------------------------------
Подробно, по шагам — отдельный раздел справки «Сообщения от нейросети» и
шаблон «Сообщение из файла» в окне «Новый скрипт».
Лимиты нейросети закончились и обновятся в 5:00. Нейросеть (или вы) пишет файл
задание.json:
    {"prompt": "Продолжи работу над проектом", "time": "05:00", "ready": true}
Скрипт ждёт задание, в нужное время вставляет текст в поле ввода и отправляет:
    wait_file("задание.json", key: "ready", value: true)   // ждать задания
    let task = read_json("задание.json")
    wait_until(task.time)                                  // дождаться 5:00
    with_window("chrome.exe") {
        click(50%, 92%)                                    // поле ввода
        paste(task.prompt)
        key("enter")
    }
    write_json("задание.json", "ready", false)             // задание сделано
    write_json("задание.json", "done", date() + " " + time())
Координаты поля ввода возьмите кнопкой «Взять координаты кликом» (Инструменты).

2. ПАРАМЕТРЫ БЕЗ ПРАВКИ СКРИПТА
-------------------------------
Числа и тексты, которые часто меняются, держите в JSON-файле: менять файл
может кто угодно, а скрипт остаётся прежним. Третий аргумент — значение,
если в файле его нет:
    let pause  = read_json("настройки.json", "pause", 1000)
    let rounds = read_json("настройки.json", "rounds", 10)
    let text   = read_json("настройки.json", "message", "Привет")
    repeat (rounds) { paste(text); key("enter"); wait(pause) }
Ключ "a.b" — значение внутри: read_json("настройки.json", "bot.name").

3. ОБЩИЕ ЗНАЧЕНИЯ ДЛЯ НЕСКОЛЬКИХ СКРИПТОВ
---------------------------------------
save_data / load_data — общая память всех скриптов (файл data.json в папке
данных). Один скрипт записал — другой прочитал, даже если оба работают:
    save_data("ход", 5)            // в скрипте «Подготовка»
    let step = load_data("ход", 0) // в скрипте «Бой»

4. ЗАПУСК СКРИПТА ДРУГОЙ ПРОГРАММОЙ
----------------------------------
Включите: Настройки → Запуск → «Разрешить запуск скриптов извне». Тогда
скрипт запускается командой (в .bat-файле, Планировщике заданий Windows или
нейросетью):
  "C:\путь\к\smart_clicker.exe" --run "Папка/Скрипт"
  "C:\путь\к\smart_clicker.exe" --stop
Если SmartClicker уже открыт, команду выполнит он (окно не выскакивает).
Занят другим скриптом — подождёт до 10 минут. В безопасном режиме и в первые
минуты после запуска с Windows команды не выполняются сразу.

4А. ЗАПУСК, КОГДА ИЗМЕНИЛСЯ ФАЙЛ
-------------------------------
Автозапуск → «По файлу» → «Добавить правило»: скрипт и файл (например,
задание.json). Нейросеть записала файл — скрипт запустился сам. Можно ждать
не любого изменения, а значения «да» по ключу (ключ ready: только когда
"ready": true). Как запускать: спросить сначала (полоса сверху окна; нет
ответа минуту — не запускается), в тестовом режиме (без кликов) или сразу —
для работы без присмотра. Файл должен не меняться 1 секунду; запуск не чаще
раза в N секунд (по умолчанию 30). Скрипт сам может сбросить задание:
    write_json("задание.json", "ready", false)

5. ВИДЕТЬ, ГДЕ СЕЙЧАС СКРИПТ
---------------------------
Настройки → Запуск → «Писать состояние скрипта в файл»: пока скрипт работает,
раз в секунду в files\state.json пишется, какой скрипт, работает ли он,
на какой строке, и его переменные; в конце — «done», «error» или «stopped».
Из самого скрипта — одной командой, в любой момент:
    export_vars("состояние.json")
Все файлы, которые читает и пишет открытый скрипт, видны прямо в программе:
вкладка «Файлы» под редактором (рядом с «Лог» и «Переменные»). Содержимое
обновляется само, когда файл меняет другая программа; его можно поправить и
сохранить там же («Изменить»), а щелчок по файлу показывает строку скрипта.

6. НЕЙРОСЕТЬ ПРАВИТ САМ СКРИПТ
------------------------------
Скрипты — обычные текстовые файлы .cks в папке scripts. Нейросеть может
прочитать скрипт, исправить и сохранить: SmartClicker это заметит за пару
секунд — новый скрипт появится в списке, открытый покажет новый текст. Если
у вас в нём несохранённые правки, сверху появится выбор: «Взять с диска»,
«Оставить своё» или посмотреть «Различия».
Подсказка для нейросети: «Справка → Скопировать промпт для ИИ» — там весь язык.

6А. НОЧНОЙ ФАРМ БЕЗ ПРИСМОТРА
-----------------------------
Скрипт работает всю ночь, а игра может вылететь или зависнуть:
  • «Автозапуск» → «Сторож»: игра (game.exe), как её запустить, скрипт —
    после вылета игра и скрипт поднимутся сами;
  • show("Собрано", count) — утром видно на мини-панели, сколько сделано;
  • все общие действия — в одном скрипте-библиотеке, подключаются use("…").

7. ОСТОРОЖНО
------------
  • Сначала запускайте чужой или новый скрипт в тестовом режиме (без кликов).
  • Защита от самоуничтожения (Настройки → Запуск) не даст скрипту
    перезагружать компьютер по кругу и писать в файлы самой программы.
  • Запуск извне по умолчанию выключен — включайте, только если он нужен.
''';
