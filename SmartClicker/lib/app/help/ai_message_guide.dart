// Help: a neural network sends a message through SmartClicker — it writes a
// task file, the script pastes the text into the chat and presses "send".

const String aiMessageGuide = r'''
СООБЩЕНИЯ ОТ НЕЙРОСЕТИ
======================

ЗАЧЕМ
-----
Нейросеть (например, ИИ-помощник, который умеет читать и писать файлы) не
может сама нажать кнопку в другой программе. SmartClicker может. Схема:
  1. нейросеть записывает задание в файл: текст и, если нужно, время;
  2. скрипт SmartClicker видит задание, открывает окно чата, вставляет текст
     в поле ввода и нажимает «Отправить»;
  3. скрипт отмечает в том же файле, что сообщение отправлено.
Пример: лимиты чата закончились и обновятся в 5:00. Нейросеть пишет задание
со временем 05:00 — и сообщение уходит в 5:00, даже если вы спите.

ШАГ 1. СКРИПТ
-------------
«Новый скрипт» → шаблон «Сообщение из файла». Заполните:
  • окно чата — имя процесса: chrome.exe, msedge.exe, telegram.exe…;
  • поле ввода — Инструменты → «от окна» → «Взять координаты кликом» и
    щелчок по полю ввода (координаты от окна, поэтому окно можно двигать);
  • файл задания — например, задание.json (лежит в папке files);
  • клавиша «Отправить» — обычно enter.
Получится скрипт, который ждёт задания по кругу:
    wait_file("задание.json", key: "ready", value: true)
    let task = read_json("задание.json")
    if (task.time) { wait_until(task.time) }
    with_window("chrome.exe") {
        click(50%, 92%)
        paste(task.prompt)
        key("enter")
    }
    write_json("задание.json", "ready", false)
Запустите его один раз — дальше он работает сам (можно свернуть в трей).

ШАГ 2. ЧТО ПИШЕТ НЕЙРОСЕТЬ
-------------------------
Файл задания (JSON):
    {"prompt": "Продолжи работу над проектом", "time": "05:00", "ready": true}
  prompt — текст сообщения; time — необязательно, «ЧЧ:ММ», когда отправить;
  ready: true — «задание готово». После отправки скрипт поставит
  "ready": false и "sent": дата и время отправки — так нейросеть видит, что
  сообщение ушло.
Где лежит папка files: Настройки → «Папка с данными» (обычно
%APPDATA%\SmartClicker\files). Нейросети можно дать такой текст:
  «Чтобы отправить сообщение, запиши в файл <полный путь>\задание.json JSON:
  {"prompt": "<текст>", "time": "<ЧЧ:ММ или пусто>", "ready": true}.
  Отправлено, когда там "ready": false и появилось поле "sent".»
Содержимое файла видно прямо в программе: вкладка «Файлы» под редактором.

ДРУГИЕ СПОСОБЫ ЗАПУСКА
---------------------
Скрипт не обязательно держать запущенным:
  • Автозапуск → «По файлу»: файл задание.json, ключ ready, «Запустить сразу»
    (тогда в скрипте не нужен repeat и wait_file — он запускается, когда
    задание готово);
  • нейросеть сама запускает скрипт командой (включите в Настройки → Запуск
    «Разрешить запуск скриптов извне»):
      "C:\путь\к\smart_clicker.exe" --run "Сообщение из файла"

ПРОВЕРИТЬ, НЕ ОТПРАВЛЯЯ
----------------------
Включите тестовый режим (кнопка «Тест без кликов») и запишите задание
вручную — в логе будет видно, что скрипт прочитал текст и куда нажал бы;
карта кликов покажет точку поля ввода.

ЕСЛИ НЕ ОТПРАВЛЯЕТСЯ
--------------------
  • Окно чата закрыто или свёрнуто — with_window выводит его вперёд, но
    вкладка с чатом должна быть открыта.
  • Поле ввода «уехало» (другой размер окна) — возьмите координаты заново
    или ищите поле картинкой: click_image("поле ввода").
  • Компьютер уснул — в 5:00 ничего не произойдёт. Отключите сон (Параметры
    Windows → Питание) или не закрывайте ноутбук.
  • SmartClicker должен быть открыт (можно в трее) или запускаться вместе с
    Windows (Настройки → «Запуск вместе с Windows»).
  • Текст вставляется через буфер обмена (paste) — то, что вы скопировали
    раньше, вернётся в буфер через полсекунды.
''';
