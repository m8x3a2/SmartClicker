// Help: the program itself — where every button is and how to do each task.
// Written so that a neural network can plan a task for the user ("press
// this, then that") without the user learning the program first.

const String appGuide = r'''
ПРОГРАММА: ГДЕ ЧТО НАЖАТЬ
=========================
Этот раздел описывает саму программу SmartClicker: разделы окна, кнопки,
настройки и как сделать каждую частую задачу. Он входит в промпт для ИИ:
нейросеть по нему составит план «что нажать и где», а скрипт напишет по
«Справочнику по языку».

ДЛЯ НЕЙРОСЕТИ: КАК ПОМОГАТЬ ПОЛЬЗОВАТЕЛЮ
---------------------------------------
  • Сначала узнайте задачу и что нужно с экрана: точки кликов, области,
    цвета, картинки-образцы, окно программы. Попросите пользователя взять
    их кнопками из раздела «КАК ПОЛУЧИТЬ…» ниже и прислать вам результат
    (координаты и цвет копируются в буфер обмена — достаточно вставить их в
    чат).
  • Давайте план по шагам с точными названиями кнопок и разделов, как они
    написаны здесь (в кавычках «…»).
  • Скрипт присылайте целиком. Пользователь создаёт скрипт («Скрипты» →
    «Новый скрипт»), вставляет код, сохраняет Ctrl+S и запускает сначала
    «Тест без кликов», потом «Запуск».
  • Если нейросеть сама может писать файлы на компьютере пользователя
    (агент), она может сразу создать скрипт и запустить его — раздел
    «НЕЙРОСЕТЬ РАБОТАЕТ САМА» в конце.
  • Картинки-образцы пользователь вырезает сам (нейросеть не видит его
    экран): скажите, какое имя дать картинке, и используйте это имя в коде.

РАЗДЕЛЫ ОКНА (колонка слева, сверху вниз)
-----------------------------------------
  • «Скрипты» — список скриптов и папок слева, редактор справа, под ним
    лог, «Переменные» и «Файлы». Над редактором: «Запуск», «Запись (F9)»,
    «Тест без кликов», «Сохранить (Ctrl+S)», переключатель «Код / Блоки /
    Блоки и код рядом», кнопка с клавиатурой (клавиша запуска этого
    скрипта) и меню ⋮ (найти и заменить, переименовать, скопировать код,
    поделиться, запустить замедленно, удалить…). Правая кнопка по скрипту
    или папке в списке — своё меню (прошлые версии, статистика, ответы на
    вопросы, импорт из ZIP, корзина).
  • «Инструменты» — координаты и цвет под курсором в реальном времени,
    «Взять координаты кликом», пипетка (взять цвет), «Выделить область»,
    переключатели «от экрана / от окна» и «Стоп-кадр», точки-ориентиры (F4),
    «Карта кликов».
  • «Автозапуск» — вкладки: расписание (один раз, каждый день, каждые
    N минут), «Для программы» (скрипт сам запускается, когда открыта
    программа), «По файлу» (запуск, когда файл изменился), «Сторож»
    (перезапуск игры и скрипта после вылета или зависания).
  • «История» — все запуски (успех, ошибка, остановлен), у ошибок —
    «Скопировать отчёт для ИИ» и «Показать в папке»; фильтры; текст скрипта
    каждого запуска.
  • «Справка» — эти разделы; кнопка «Скопировать промпт для ИИ» сверху;
    «Выгрузить всю справку в ZIP» рядом с ней.
  • «Картинки» — «Картинки и текст на экране»: последняя выделенная область,
    сохранённые картинки-образцы, распознавание текста, готовые команды.
  • «Буфер» — история буфера обмена (включается там же), Win+Alt+V.
  • «Настройки» — все настройки по карточкам (ниже), «Папка с данными».
  • Внизу колонки — кнопка мини-панели: окно сворачивается в узкую панель
    поверх всех окон.

КАК ПОЛУЧИТЬ ТОЧКУ (КООРДИНАТЫ КЛИКА)
------------------------------------
Способ 1 — в буфер обмена: «Инструменты» → «Взять координаты кликом» (или
на мини-панели значок прицела). Экран замирает (стоп-кадр), окно программы
становится мини-панелью; кликните в нужное место. Клик никуда не попадёт,
кнопки под мышью не подсвечиваются, рядом с курсором — лупа ×8. В буфере
окажется «x, y» (или проценты — смотря «Формат координат» в настройках).
Отмена — Esc, правая кнопка мыши или крестик на мини-панели.
  • Переключатель «от окна» рядом: в буфер попадёт готовая строка
    with_window("окно") { click(x, y) } — координаты от окна, клик сработает,
    даже если окно сдвинуть.
Способ 2 — прямо в скрипт: поставьте курсор в редакторе на пустую строку,
наведите мышь на нужное место экрана и нажмите F6 — вставится
click(x, y) с комментарием о цвете.
Способ 3 — в конструкторе блоков: у блока значок прицела.

КАК ПОЛУЧИТЬ ЦВЕТ
----------------
  • «Инструменты» → кнопка с пипеткой (или пипетка на мини-панели) →
    кликнуть по стоп-кадру: в буфере обмена цвет вида #RRGGBB.
  • Цвет под курсором всё время виден на «Инструментах» и на мини-панели.
  • F6 вставляет клик с комментарием «цвет #…».
  • У блока wait_pixel прицел берёт и точку, и цвет сразу.

КАК ПОЛУЧИТЬ ОБЛАСТЬ (x, y, ширина, высота)
------------------------------------------
«Инструменты» → «Выделить область» (то же в «Картинках», в быстрых
настройках записи, Ctrl+K → «Выделить область»). Экран замирает — обведите
область мышью: нажать в левом верхнем углу, вести, отпустить в правом
нижнем (или отметить углы клавишей Ctrl). В буфере обмена — «x, y, w, h»,
и открывается раздел «Картинки» с этой областью: там готовые команды
(прочитать текст, ждать текст, число, координаты области).

КАК ВЫРЕЗАТЬ КАРТИНКУ-ОБРАЗЕЦ (для find_image / click_image)
-----------------------------------------------------------
Выделите область, как выше, вокруг кнопки или значка. В разделе «Картинки»
в поле «ИМЯ КАРТИНКИ» введите имя (например, «кнопка старт») → «Сохранить».
В скрипте: click_image("кнопка старт"). Там же у сохранённой картинки:
«Где используется», «Переименовать», «Заменить снимком». Советы, какой кусок
вырезать, — раздел справки «Картинки и текст».

КАК ПРОЧИТАТЬ ТЕКСТ ИЛИ ЧИСЛО С ЭКРАНА
-------------------------------------
Выделите область с текстом → в «Картинках» видно, что распозналось, и
кнопки с готовыми командами: «Весь текст области», «Число из области»,
«Ждать, пока текст появится», «Какой текст искать в этой области».
Способ распознавания (PaddleOCR / Windows) выбирается там же. Подробно —
раздел «Распознавание текста».

КАК ЗАПИСАТЬ ДЕЙСТВИЯ
--------------------
Открыть (или создать) скрипт → «Запись (F9)» → после отсчёта делать всё
мышью и клавиатурой → F9 ещё раз. Код появится в редакторе. Что записывать
(только клики / клики + остановки курсора / полная траектория) — значок
быстрых настроек над редактором или «Настройки» → «Запись действий».
Призрак (F3 во время записи): клики и клавиши записываются, но до программ
не доходят — так записывают «Отправить», ничего не отправив.

КАК ЗАПУСТИТЬ И ОСТАНОВИТЬ
-------------------------
  • «Запуск» над редактором (отсчёт перед запуском — в настройках),
    «Тест без кликов» — то же, но клики только показываются.
  • Клавиша для одного скрипта — кнопка с клавиатурой над редактором.
  • Призрак (F3, или 👻 на мини-панели и в полосе над редактором): пока
    скрипт работает, его клики и клавиши только показываются кольцом и в
    логе, но не нажимаются. Так проверяют важное нажатие: дойти до него,
    включить призрака, посмотреть, куда попадает клик, выключить.
  • F12 — аварийная остановка, Esc — тоже стоп, F8 — пауза. Ещё один
    способ — увести мышь в угол экрана (включается в настройках).
  • Мини-панель: запуск, пауза, стоп, запись, координаты и цвет.
  • По расписанию, при открытии программы, по изменению файла — раздел
    «Автозапуск».

ЕСЛИ СКРИПТ ОШИБСЯ
-----------------
«История» → запуск с ошибкой → «Скопировать отчёт для ИИ» и вставить в чат:
там ошибка, строка, лог, настройки и снимок экрана в момент ошибки (снимок —
в ZIP «Показать в папке»). Проверка перед запуском находит опечатки,
неизвестные переменные и картинки, которых нет. Пошаговая отладка: точка
останова — щелчок по номеру строки, затем «Шаг»; вкладка «Переменные».

НАСТРОЙКИ (раздел «Настройки», карточки сверху вниз)
---------------------------------------------------
У каждой карточки — «Сбросить» (значения по умолчанию только этой карточки).
  • Общее: «Формат координат» (пиксели или проценты), «Показывать место
    клика на экране» (отметка перед каждым кликом), «Вид отметки клика»
    (точка, кольцо или перекрестие; цвет, размер, значок глаза — показать).
  • Редактор: подсказки при наборе, пояснения при наведении мыши.
  • Мини-панель поверх всех окон: свернуть, клавиша свернуть/развернуть,
    «Сворачивать в панель на время работы скрипта».
  • Трей: «Сворачивать в трей», «Закрывать в трей».
  • Горячие клавиши (работают в любой программе): аварийная остановка
    (F12), ещё одна клавиша остановки (Esc), остановка мышью в угол, пауза
    (F8), запись (F9), вставить точку под курсором (F6), точка-ориентир
    (F4), призрак — запись и работа скрипта (F3), запустить открытый скрипт, «Не
    пропускать эти клавиши в другие программы». Назначить: нажать кнопку
    справа от строки, затем клавишу или сочетание.
  • Запуск: отсчёт перед запуском, остановить через N минут, после N
    повторений циклов, «Проверять скрипт перед запуском», перезапуск после
    ошибки и пауза перед ним, сторожевой таймер, пауза после каждого
    действия, пауза для «Запустить замедленно», «Разрешить скриптам
    выключать компьютер», «Защита от самоуничтожения», «Разрешить запуск
    скриптов извне», «Писать состояние скрипта в файл».
  • Запись действий: отсчёт, что записывать от мыши, порог остановки
    курсора, привязка к окнам, клики только в своё окно, текст как type(),
    системные сочетания, умные паузы.
  • Человекоподобное поведение: плавные движения мыши, разброс кликов
    (± px), разброс пауз wait (± %), пауза между буквами type() — значения
    по умолчанию для всех скриптов.
  • Логи и уведомления: лог каждого запуска в файл, отчёт при ошибке
    (скрипт, лог, снимок экрана), сколько хранить истории и текст скрипта
    в ней, сколько секунд показывать плашку.
  • Запуск вместе с Windows: запускать при входе, сразу в трей, задержка
    автоматики после запуска.
  • Папка с данными: где лежит, перенести, резервная копия всего, копия
    каждый день, прошлые версии скриптов, «Сбросить всё».
  • История буфера обмена и её лимиты — в разделе «Буфер»; способ
    распознавания текста — в разделе «Картинки».
Быстрые настройки записи и запуска — значок над редактором.

ПАПКА С ДАННЫМИ
--------------
«Настройки» → «Папка с данными» → «Открыть». Внутри: scripts (скрипты .cks,
папки — подпапки), files (картинки .png и файлы скриптов: JSON, txt),
notes (заметки), logs, reports (отчёты об ошибках), settings.json,
history.json, data.json (save_data/load_data). По умолчанию это
%APPDATA%\SmartClicker; может быть папка userdata рядом с программой или
выбранная в настройках.

НЕЙРОСЕТЬ РАБОТАЕТ САМА (агент с доступом к файлам)
--------------------------------------------------
  1. Написать скрипт: файл scripts\Имя.cks (UTF-8) в папке с данными;
     подпапка — папка в списке. Программа увидит новый скрипт за 2 секунды.
     Открытый скрипт с несохранёнными правками не перезаписывается молча —
     пользователь выберет «Взять с диска» или «Оставить своё».
  2. Запустить: smart_clicker.exe --run "Папка/Имя" (имя — путь от scripts
     без .cks, через /). Остановить: smart_clicker.exe --stop. Работает,
     пока включена настройка «Разрешить запуск скриптов извне» (включена по
     умолчанию); пользователь видит полосу «запущен извне» с кнопкой «Стоп».
  3. Узнать результат: «Писать состояние скрипта в файл» → files\state.json
     (скрипт, строка, состояние, переменные), или в скрипте
     export_vars("итог.json"); логи — папка logs, история — history.json.
  4. Данные пользователя (координаты, тексты) удобно передавать через JSON:
     read_json("параметры.json", "x", 100) — раздел «Идеи использования».
  Сначала запускайте новый скрипт в тестовом режиме или убедитесь вместе с
  пользователем, что клики пойдут туда, куда нужно.
''';
