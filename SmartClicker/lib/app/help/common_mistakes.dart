// Help: typical mistakes and what to do about them.


const String commonMistakes = r'''
ЧАСТЫЕ ОШИБКИ И НЕДОПОНИМАНИЯ
=============================

0. ЧЕМ use_screen() ОТЛИЧАЕТСЯ ОТ use_window() (самое важное)
-------------------------------------------------------------
Координаты — это всегда «сколько от левого верхнего угла чего-то». Вопрос —
от угла ЧЕГО:
  • use_screen() (так по умолчанию) — от угла ЭКРАНА. click(50%, 50%) —
    середина монитора, где бы ни было окно.
  • use_window("claude.exe") — от угла ОКНА этой программы (его рабочей
    части, без заголовка). click(50%, 50%) — середина окна, даже если окно
    сдвинули, сделали меньше или оно на другом месте.

Пример: окно занимает правую половину экрана.
    use_screen()               click(75%, 50%)   // середина окна
    use_window("claude.exe")   click(50%, 50%)   // та же точка!
Одна и та же кнопка имеет РАЗНЫЕ числа в этих двух режимах. Поэтому:
  • запись с привязкой к окну пишет use_window(...) и проценты ОКНА.
    Закомментируете use_window — те же числа будут считаться от экрана, и
    клик уйдёт в другое место. Даже РАЗВЁРНУТОЕ окно не совпадает с экраном:
    оно не заходит на панель задач (внизу ~50–70 точек), поэтому 90% высоты
    окна выше, чем 90% высоты экрана. Пример: 90.58% окна — y = 913, а 90.58%
    экрана 1080 — y = 978, это уже ниже кнопки;
  • «Взять координаты кликом» (Инструменты) и подсказка у курсора дают
    координаты ЭКРАНА. Вставили их после use_window — промах. Под use_window
    берите точку клавишей F6: она сама считает от окна (см. пункт 2).
Зачем вообще use_window: окно можно двигать и менять ему размер — клики
по-прежнему попадают в те же кнопки. С use_screen окно должно стоять ровно
там же, где было при записи.

focus_window("claude.exe") — другое: просто выводит окно на передний план
(как щелчок по нему на панели задач), координаты не меняет.
require_window("claude.exe") — защита: клики и клавиши идут только в это
окно; если сверху другое окно, скрипт сам выводит нужное вперёд и кликает.
require_window("claude.exe", focus: false) — не выводить, а ждать, пока окно
сделают активным (пункт 3). Без require_window скрипт, у которого окно
перекрыли, кликнет по тому, что сверху.

ПРОЩЕ ВСЕГО — with_window: всё сразу и только внутри фигурных скобок.
    with_window("claude.exe") {
        click(50%, 90%)       // координаты от окна, клик — только в него
        type("Привет")
    }
    click(75%, 50%)           // после блока — снова от экрана, как было
Внутри блока действуют use_window + require_window; после закрывающей скобки
всё возвращается как было — use_screen() и require_window(null) писать не
нужно. Даже если внутри случилась ошибка (try/catch) или break.

1. ПОСЛЕ use_window() КЛИКИ ПОПАДАЮТ НЕ ТУДА
---------------------------------------------
use_window("notepad") и require_window("notepad") действуют ДО КОНЦА СКРИПТА,
а не только внутри своих фигурных скобок (только в своих скобках действует
with_window("notepad") { ... } — см. пункт 0). Все следующие координаты считаются
от окна Блокнота, а клики ждут, пока Блокнот станет активным.

Если дальше нужно работать со всем экраном, сбросьте привязку:

    use_screen()            // координаты снова от всего экрана
    require_window(null)    // ввод больше не ждёт конкретное окно

Запись (F9) вставляет эти две строки сама. Если вы склеиваете куски скриптов
вручную — проверьте, что они есть перед «экранной» частью.

2. В КАКИХ КООРДИНАТАХ ВСТАВЛЯЕТСЯ ТОЧКА ПО F6
----------------------------------------------
F6 смотрит, что написано в скрипте ВЫШЕ текстового курсора:
  • выше стоит use_window("Game") и мышь наведена на окно Game — координаты
    считаются от этого окна;
  • выше стоит use_window("Game"), а мышь наведена на другое место — перед
    кликом вставится use_screen(), координаты от экрана;
  • привязки нет — координаты от экрана. Если в режиме записи включено
    «Привязывать к окнам», F6 сам вставит use_window("окно") перед кликом.
Поэтому ставьте текстовый курсор в то место скрипта, куда нужна точка.

3. СКРИПТ «ВИСИТ» И ПИШЕТ «Окно ... не активно — жду»
-----------------------------------------------------
Это работает require_window(): пока нужное окно не на переднем плане, клики и
клавиши не выполняются — это защита от кликов «мимо» по рабочему столу.
Обычно скрипт сам выводит окно вперёд; ждёт он, если окна нет (закрыто,
не найдено по имени) или написано focus: false. Откройте окно, проверьте
имя или снимите защиту: require_window(null).

4. ЗАПИСЬ ПРОМАХИВАЕТСЯ ПРИ ПОВТОРЕ
-----------------------------------
Запись запоминает места на экране, а не кнопки. Если окно при повторе стоит в
другом месте, другого размера или раскрыто иначе — клик попадёт мимо.
Что делать:
  • в начале скрипта ставьте окно в одно и то же положение:
        focus_window("Game")
        set_window_bounds("Game", 0, 0, 1280, 720)
  • включите «Привязывать к окнам» в режиме записи — запись сама вставит
    focus_window и будет считать координаты от окна;
  • если нужно навести мышь, чтобы что-то раскрылось, — режим записи
    «Клики + остановки курсора» или «Полная траектория»;
  • не переключайте окна кликами по панели задач — пишите focus_window("...");
  • если открыто несколько окон одной программы, панель задач показывает
    миниатюры на выбор, и запись такого клика ненадёжна. Указывайте окно по
    части заголовка: focus_window("Без имени") или focus_window("отчёт.txt").

5. НЕСКОЛЬКО ОКОН ОДНОЙ ПРОГРАММЫ
---------------------------------
focus_window("notepad") берёт первое подходящее окно (верхнее). Чтобы выбрать
конкретное, ищите по части заголовка, а не по имени процесса. Список окон с
заголовками — на вкладке «Инструменты» или командой log(windows()).

6. key("g") ПЕЧАТАЕТ «п» ВМЕСТО «g»
-----------------------------------
key() нажимает физическую клавишу, поэтому результат зависит от текущей
раскладки клавиатуры. Для текста используйте type("привет") или
paste("привет") — они вводят именно эти буквы при любой раскладке.

7. launch() НЕ ОТКРЫЛ ПРОГРАММУ
-------------------------------
Если программа уже запущена, launch() не открывает вторую копию и возвращает
false. Нужна ещё одна копия — launch("notepad.exe", new: true).

8. БЕСКОНЕЧНЫЙ ЦИКЛ БЕЗ ПАУЗЫ
-----------------------------
    repeat { click(50%, 50%) }     // тысячи кликов в секунду!
Всегда ставьте wait() внутри цикла. Остановить можно клавишей аварийной
остановки (по умолчанию F12). В настройках есть лимиты времени и числа циклов.

9. КЛИКИ НЕ ДОХОДЯТ ДО ПРОГРАММЫ
--------------------------------
  • Программа запущена от администратора — запустите SmartClicker тоже от
    администратора (ограничение Windows). Настройки → «Доступы» покажет,
    какие открытые программы запущены так, и перезапустит SmartClicker.
  • Некоторые игры с античитом не принимают программный ввод — это не лечится.
  • Игре нужно время: добавьте hold к клику — click(x, y, hold: 80).

10. СКРИПТ НЕ СОХРАНИЛСЯ
------------------------
Запуск НЕ сохраняет скрипт — выполняется то, что сейчас в редакторе.
Сохранить: Ctrl+S или кнопка с дискетой. Несохранённые скрипты отмечены
точкой ●. Кнопка «Сбросить» возвращает последний сохранённый вариант.

11. ПРОЦЕНТЫ И ОСТАТОК ОТ ДЕЛЕНИЯ
---------------------------------
50% — это проценты, а 10 % 3 (с пробелами) — остаток от деления.

12. find_image / click_image НЕ НАХОДИТ КАРТИНКУ
------------------------------------------------
Без scale картинка ищется ровно того размера, каким её вырезали. Если окно
игры стало другого размера, сменилось разрешение экрана или масштаб Windows,
добавьте scale: "auto" (от 0.5 до 2 размеров) или свой диапазон 0.8..1.3.
Если кнопка подсвечивается под курсором или мигает — вырежьте её в обычном
состоянии или увеличьте tolerance: 40. Найденный масштаб покажет
log(find_image("имя", scale: "auto")) — потом его можно указать числом.

13. type("...") ПЕЧАТАЕТ НЕ ВСЁ («Прив» вместо «Привет»)
------------------------------------------------------
Программы принимают буквы с задержкой. Если отправить их все разом, часть
теряется — особенно в Блокноте Windows 11. Поэтому type по умолчанию
делает паузу 50 мс между буквами (Настройки → «Человекоподобное
поведение» → «Пауза между буквами»). Если буквы всё равно теряются —
увеличьте паузу: type("Привет", delay: 100). Длинный текст быстрее и
надёжнее вставить: paste("текст") (через буфер обмена).
''';
