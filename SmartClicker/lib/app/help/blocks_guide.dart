// Help: the block constructor.


const String blocksGuide = r'''
КОНСТРУКТОР БЛОКОВ
==================
Скрипт можно не набирать, а собрать из блоков мышью — как в Scratch.
Блоки и код — одно и то же: блоки строятся из кода, а каждая правка
блока сразу записывается в код. Комментарии и ваше оформление
сохраняются.

ПЕРЕКЛЮЧАТЕЛЬ — справа над редактором:
  • «Код» — обычный редактор;
  • «Блоки» — только блоки;
  • «Блоки и код рядом» — правка в одном сразу видна в другом; границу
    между ними можно двигать мышью. Текстовый курсор в коде подсвечивает
    свой блок.

СОБРАТЬ СКРИПТ
--------------
  • Слева — категории (Мышь, Клавиши, Ожидание, Экран…) и их блоки.
    Строка «Найти блок…» ищет по словам: «картинка», «цвет», «ждать».
  • Блок перетаскивают мышью в скрипт: синяя полоса показывает, куда он
    встанет. Внутрь «повторить» и «если» — на пустое место «перетащите
    блоки сюда» или на нижнюю половину заголовка.
  • Щелчок по блоку в списке — он встаёт после выделенного блока
    (или в конец).
  • Готовый блок двигают за название или за значок ⋮⋮ слева. Брошенный
    на список блоков — удаляется.

ПАРАМЕТРЫ
---------
  • У каждого блока все параметры на виду: белые поля — числа и текст,
    оранжевые — переменные. Текст пишется без кавычек — они добавятся
    сами.
  • Наведите мышь на блок или поле — появится пояснение: что делает блок,
    что значит параметр, в каких единицах число (50% — проценты, 1s —
    секунда), как выглядит картинка.
  • Значок ⊕ — добавить необязательный параметр: кнопку мыши, разброс,
    сколько ждать (timeout), точку или область. Крестик — убрать.
  • Прицел — взять точку кликом прямо на экране (у wait_pixel заодно и
    цвет), значок рамки — выделить область двумя нажатиями Ctrl.
    Если выше блока стоит use_window, координаты будут от окна.
  • Рядом с полями картинки, окна, скрипта — список для выбора, у
    клавиши — «нажать клавишу».
  • Значения (цвет точки, найти картинку, сравнение «=», «и», «не»)
    перетаскивают прямо в поле другого блока. Например, в «если»:
    «если [цвет точки 50% 50%] = "#FFFFFF"».
  • Правая кнопка на поле — ввести как код (pos.x + 10) или подставить
    переменную.

ПРАВКА
------
  • Щелчок по блоку выделяет его. Del — удалить, Ctrl+D — копия,
    Ctrl+C / Ctrl+X / Ctrl+V — через буфер (вставляется и код из
    другого места), Alt+↑ / Alt+↓ — передвинуть, ↑ / ↓ — соседний блок,
    Ctrl+Z / Ctrl+Y — отменить и вернуть.
  • Правая кнопка на блоке: дублировать, «иначе если», «иначе»,
    комментарий, точка останова, «Изменить как код…».
  • Число справа на блоке — номер строки; щелчок ставит точку останова.
  • Чего нет среди блоков, показывается серым блоком «код» — его можно
    править как текст.

ЗАПУСК
------
  Во время работы выполняемый блок обводится белым, блок с ошибкой —
  красным. Если в коде синтаксическая ошибка, блоки показывают последнее
  правильное состояние и пишут, где ошибка («Показать в коде»).

ПРИМЕР: то, что собирается за минуту
    repeat (10) {
        if (pixel_is(50%, 50%, "#FFFFFF")) {
            click(50%, 50%)
        }
        wait(1s)
    }
''';
