// Help: recognition of text (OCR) step by step — choosing an area, its
// coordinates, reading once or regularly, keeping the answers.

const String ocrGuide = r'''
РАСПОЗНАВАНИЕ ТЕКСТА (OCR)
==========================

Программа умеет читать текст прямо с экрана: надпись, число, ответ в окне.
Нужно только сказать, ГДЕ читать — прямоугольник экрана (область).

ШАГ 1. ВЫДЕЛИТЬ ОБЛАСТЬ
-----------------------
«Инструменты» → «Выделить область» (та же кнопка — в быстрых настройках и в
разделе «Картинки и текст»; или Ctrl+K → «Выделить область»):
экран замирает (стоп-кадр) — обведите текст мышью: нажмите в левом верхнем
углу, ведите и отпустите в правом нижнем (или отметьте углы клавишей Ctrl).
Клик никуда не попадёт: он приходится на стоп-кадр. Рядом с курсором —
лупа. Esc или правая кнопка — отменить.

ШАГ 2. ПРОВЕРИТЬ, ЧТО ПРОЧИТАЛОСЬ
--------------------------------
Сразу откроется раздел «Картинки и текст»:
  • слева — что попало в область, справа — какой текст там прочитан;
  • ниже — готовые команды: read_text(…), read_number(…), text_in(…).
    Нажмите на команду — она скопируется, вставьте её в скрипт (Ctrl+V);
  • кнопка, на которой написаны одни четыре числа, копирует только координаты
    области (подсказка «Только координаты»).
Если текст прочитался плохо — выделите плотнее (без значков и рамок рядом)
или переключите способ распознавания там же (см. ниже).

ШАГ 3. КООРДИНАТЫ ОБЛАСТИ
-------------------------
Четыре числа: x, y, ширина, высота — от левого верхнего угла ЭКРАНА.
Программа пишет их в процентах (10%, 20%, 30%, 10%) — тогда скрипт работает и
на другом разрешении экрана; в пикселях тоже можно (192, 216, 576, 108) —
формат выбирается в «Настройки» → «Общее» → «Формат координат».
Окно с текстом должно стоять там же, где было при выделении: сдвинули окно —
выделите область заново (или разверните окно на весь экран — тогда оно всегда
на месте).

ШАГ 4. ПРОЧИТАТЬ В СКРИПТЕ
-------------------------
    let text = read_text(10%, 20%, 30%, 10%)     // весь текст области
    log("прочитано:", text)

    let gold = read_number(80%, 2%, 10%, 4%)     // число (счётчик, цена) или null

    if (text_in(10%, 20%, 30%, 10%, "Готово")) { // есть ли там слово
        click(50%, 60%)
    }

    wait_text(10%, 20%, 30%, 10%, "Готово", timeout: 2m)   // дождаться слова

Текст похож, но распознался с ошибкой? Сравнивайте нестрого:
    if (similar(text, "Начать")) { log("похоже на «Начать»") }
    text_in(10%, 20%, 30%, 10%, "враг", errors: 1)   // разрешить одну ошибку

ШАГ 5. ЧИТАТЬ РЕГУЛЯРНО
----------------------
Раз в N минут — цикл с паузой:
    repeat {
        let text = read_text(10%, 20%, 30%, 10%)
        log(text)
        wait(5m)
    }
Читать, только когда в области что-то изменилось (экономнее):
    repeat {
        wait_change(10%, 20%, 30%, 10%, timeout: 0)   // ждать изменения сколько угодно
        wait_still(10%, 20%, 30%, 10%, still: 2s)     // дождаться, пока текст допишется
        log(read_text(10%, 20%, 30%, 10%))
    }
Не мешая основному циклу — реакция по времени:
    every(5m, () => { log(read_text(10%, 20%, 30%, 10%)) })

ШАГ 6. СОХРАНИТЬ ОТВЕТЫ
----------------------
В переменную — до конца запуска:
    let last = read_text(10%, 20%, 30%, 10%)
В массив — все ответы по порядку:
    let answers = []
    answers.push(read_text(10%, 20%, 30%, 10%))   // добавить в конец
Работа с массивом:
  • answers[0] — первый, не удаляя; answers[answers.length - 1] — последний;
  • answers.shift() — взять первый и убрать его; answers.pop() — последний;
  • answers.length — сколько; answers.includes(t) — есть ли уже такой.
В «стопку» для вставки в другую программу:
  • clip_add(text) — положить; paste_next() — вставить первый (Ctrl+V в
    активное окно) и убрать его; paste_all() — всё разом; clip_count().
Между запусками и для других скриптов:
  • save_data("ответы", answers) — запомнить; load_data("ответы", []) — прочитать;
  • write_json("ответы.json", "last", text) — в файл (его может читать нейросеть).
На мини-панели во время работы:
    show("Последний", text)

ДВА СПОСОБА РАСПОЗНАВАНИЯ
------------------------
  Точное (PaddleOCR) — по умолчанию. Около секунды, хорошо читает мелкий,
                       цветной и игровой текст.
  Быстрое (Windows)  — доли секунды, только для чёткого обычного текста.
Выбирается в разделе «Картинки и текст»; для одной команды — в скрипте:
    read_text(10%, 20%, 30%, 10%, engine: "windows")

ГОТОВЫЙ СКРИПТ
--------------
В списке скриптов — «Чтение области каждые 5 минут» (если его нет — скопируйте
отсюда): читает область, копит ответы в массив и в «стопку», показывает их
число на мини-панели. Поправить в нём нужно только ОБЛАСТЬ и ПАУЗУ.
    let ОБЛАСТЬ = [10%, 20%, 30%, 10%]
    let ПАУЗА = 5m
    let answers = []
    let last = ""
    repeat {
        let text = read_text(ОБЛАСТЬ[0], ОБЛАСТЬ[1], ОБЛАСТЬ[2], ОБЛАСТЬ[3]).trim()
        if (text != "" && text != last) {
            answers.push(text)
            clip_add(text)
            last = text
            log("новый ответ:", text)
        }
        show("Ответов", answers.length)
        wait(ПАУЗА)
    }

ЕСЛИ ЧИТАЕТ ПЛОХО
-----------------
  • Выделяйте плотно — только нужную строку, без значков и рамок.
  • Мелкий текст: окно крупнее или масштаб больше; scale: 3 — увеличить область
    перед распознаванием: read_text(10%, 20%, 30%, 10%, scale: 3).
  • Числа — через read_number: он сам уберёт лишние символы.
  • Не сравнивайте через ==, а через text_in / similar — распознавание
    ошибается в мелочах (о/0, l/1).
''';
