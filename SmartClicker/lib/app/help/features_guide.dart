const String featuresGuide = r'''
ВОЗМОЖНОСТИ SMARTCLICKER
========================
Коротко обо всём, что умеет программа. Подробности — в других разделах
справки.

СКРИПТЫ
-------
  • Скрипт — обычный текст на простом языке: click, wait, key, type, if,
    repeat… Полный список команд — «Справочник по языку».
  • Готовые шаблоны: автокликер, анти-AFK, дождаться кнопки, награда каждые
    N минут и другие — кнопка «Новый скрипт».
  • Запись действий (F9): программа сама пишет скрипт по вашим кликам,
    клавишам, тексту, колесу мыши; три режима — только клики, с остановками
    курсора, полная траектория.
  • Папки, перетаскивание, переименование, экспорт и импорт в ZIP.
  • Поделиться скриптом (правая кнопка по скрипту или ⋮ над редактором):
    один ZIP со скриптом, его картинками и скриптами из run_script. При
    импорте («Скрипты» → ⋮ → «Импорт из ZIP…») видно, что добавится (свой
    скрипт с тем же именем можно оставить, заменить или сравнить), а
    опасные команды чужого скрипта (run_command, system_power, launch…)
    показываются заранее, с номерами строк.
  • Скрипты вызывают друг друга (run_script) — общие функции можно держать
    в одном месте. Переименовали или перенесли скрипт — программа покажет,
    где его вызывают, и исправит отмеченные вызовы на полный путь
    ("Папка/Имя"). Проверка предупредит, если короткое имя подходит к
    нескольким скриптам.
  • Работа с одним окном: with_window("окно") { ... } — внутри блока
    координаты от окна, а клики только в него (перекрыли — выведет вперёд);
    после блока всё как было. «Взять координаты кликом» в режиме «от окна»
    сразу даёт такую строку.
  • Вопросы при запуске: ask("Сколько раз?", 10) — при нажатии «Запуск»
    появится окно с полем, не нужно править код ради одного числа. Ответ
    запоминается; при запуске по клавише или расписанию берётся последний.
    Поменять ответы: «?» на мини-панели, Shift + клавиша скрипта или правая
    кнопка по скрипту → «Ответы на вопросы…».
  • Ctrl+Z / Ctrl+Y — у каждого скрипта своя история правок, переключение
    между скриптами её не теряет.
  • Правая кнопка по папке → «Прогнать все скрипты папки без кликов»: все
    скрипты по очереди в тестовом режиме и одна сводка (для «Проверок» —
    как задумано или нет).
  • Редактор: подсветка, подсказки при наборе и при наведении, поиск и
    замена, картинка при наведении на её имя, F6 — вставить координаты.
  • Конструктор блоков: скрипт собирается мышью из блоков, все параметры
    видны и подписаны, при наведении — пояснения. Можно смотреть блоки и
    код рядом: правка в одном сразу видна в другом. Переключатель — справа
    над редактором (раздел справки «Конструктор блоков»).

КЛИКИ И КЛАВИАТУРА
------------------
  • Клики, удержание, перетаскивание, колесо, движение по траектории;
    координаты в пикселях или процентах экрана.
  • Клавиши и сочетания, набор текста на любом языке.
  • «Как человек»: случайный разброс точек и пауз, плавное движение мыши.
  • Привязка к окну: координаты от угла окна, работа только пока окно
    активно.

ЗРЕНИЕ
------
  • Цвет точки: проверить, дождаться (pixel_is, wait_pixel).
  • Поиск картинки на экране и клик по ней, в том числе другого размера
    (scale).
  • Чтение текста и чисел с экрана — точное (PaddleOCR) или быстрое
    (Windows).
  • Раздел «Картинки»: вырезать кусок экрана, сохранить, проверить
    распознавание, получить готовые команды. Правая кнопка по картинке:
    где используется, переименовать (скрипты исправятся после
    подтверждения), заменить снимком (имя то же), удалить.

ЗАПУСК И УПРАВЛЕНИЕ
-------------------
  • Горячие клавиши: запуск, пауза, стоп (F12 — аварийная остановка из
    любой программы), запись, своя клавиша для любого скрипта. Сработавшая
    клавиша не доходит до активной программы (F12 не откроет инструменты
    разработчика в браузере); пока ничего не запущено, F12 и F8 — обычные.
    Esc — вторая клавиша остановки. По желанию — остановка «мышь в угол»:
    резко увести мышь в угол экрана (Настройки → Горячие клавиши).
  • Мини-панель поверх всех окон и сворачивание в трей.
  • Папка с данными (Настройки): своя папка (например, в OneDrive) или
    «Рядом с программой» — программу со всеми скриптами можно носить на флешке.
  • Резервная копия всего одним ZIP и восстановление из неё, «Сбросить всё»
    (как после установки) — там же, в Настройках → «Папка с данными».
  • Запуск вместе с Windows (Настройки): программа сама стартует при входе
    в Windows и ждёт у часов — расписание работает и после перезагрузки.
  • Автозапуск: по расписанию (один раз в нужный день и час, каждый день в
    заданное время, каждые N минут) и по программе (когда она запустилась
    или её окно стало активным). Задачу можно изменить (✎).
  • Защита: лимиты времени и числа повторов, тестовый режим без кликов,
    перезапуск после ошибки (по желанию).
  • Скрипты-проверки настроек: «Скрипты» → ⋮ → «Добавить скрипты-проверки
    настроек» — папка «Проверки»: стоп и пауза, мышь в угол, тестовый режим,
    лимиты, перезапуск, вопросы при запуске… В начале каждого написано, что
    включить и что должно произойти.
  • Настройки → «Доступы»: что работает на этом компьютере и что мешает
    (например, программы, запущенные от администратора), с кнопками
    исправления.

ОТЛАДКА
-------
  • Проверка скрипта перед запуском: опечатки, неизвестные переменные,
    картинки, которых нет, бесконечный цикл без паузы.
  • Подсветка текущей строки, пошаговый режим, точки останова.
  • Вкладка «Переменные»: значения во время работы.
  • Лог каждого запуска, история, уведомления.
  • Отчёт об ошибке одним файлом: скрипт, лог, переменные, снимок экрана;
    его можно сразу отдать нейросети.

СИСТЕМА
-------
  • Окна: найти, активировать, переместить, изменить размер.
  • Программы: запустить, проверить, закрыть.
  • Загрузка процессора и памяти, заряд батареи, есть ли интернет, буфер
    обмена, всплывающие уведомления, запуск команд.
  • Выключение, перезагрузка, сон — только с разрешением в настройках.
  • Данные между запусками (save_data / load_data), файлы, время и даты.

НЕЙРОСЕТЬ В ПОМОЩЬ
------------------
  • «Скопировать промпт для ИИ» — справка по языку, частые ошибки и ваши
    заметки одним текстом: вставьте в чат и опишите задачу.
  • «Мои заметки» — свои подсказки, они тоже попадают в промпт.
''';
