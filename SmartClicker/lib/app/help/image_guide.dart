// Help: pictures and text on the screen (find, click, read).


const String imageGuide = r'''
КАРТИНКИ И ТЕКСТ НА ЭКРАНЕ
==========================

ЗАЧЕМ ЭТО НУЖНО
---------------
Координаты ломаются, когда окно сдвинулось, кнопка переехала или игра
загрузилась медленнее обычного. Надёжнее, чтобы скрипт СМОТРЕЛ на экран:
  • нашёл кнопку по её виду и нажал на неё — поиск картинки;
  • прочитал надпись или число — распознавание текста;
  • дождался, пока нужное появится, вместо того чтобы ждать «на глаз».

ШАГ 1. ВЫРЕЗАТЬ КУСОК ЭКРАНА
----------------------------
Вкладка «Инструменты» → «Выделить область» (кнопка есть и в быстрых
настройках, и в мини-панели):
  1. наведите курсор на левый верхний угол нужного места и нажмите Ctrl;
  2. наведите на правый нижний угол — и снова Ctrl.
Пока вы ведёте курсор, область обведена красной рамкой. Ctrl, а не клик —
чтобы не нажать то, что под курсором.

Сразу откроется раздел «Картинки и текст». В нём видно:
  • что именно попало в область;
  • какой текст программа там прочитала;
  • готовые команды — нажмите на нужную, она скопируется, вставьте в скрипт;
  • поле имени и «Сохранить» — чтобы потом искать эту картинку.
Сохранённые картинки — слева в том же разделе. Это обычные файлы .png
в папке files (значок папки рядом с заголовком списка).

ШАГ 2. НАЙТИ И НАЖАТЬ КАРТИНКУ
------------------------------
    click_image("старт")                    // нажать, если кнопка видна
    click_image("старт", timeout: 10s)      // подождать её до 10 секунд
    wait_image("старт", timeout: 1m)        // просто дождаться появления

    p = find_image("старт")                 // где она? {x, y} или null
    if (p) {
        log("кнопка на", p.x, p.y)
        click(p)
    } else {
        log("кнопки нет")
    }

click_image возвращает true, если нашёл и нажал, и false, если нет — это
можно проверять в if. Нажимает в центр картинки.

Наведите мышь на имя картинки в кавычках — редактор покажет саму картинку
и её размер. Если такого файла нет, подсказка скажет об этом сразу.

КАКУЮ КАРТИНКУ ВЫРЕЗАТЬ
-----------------------
Хороший образец — небольшой и узнаваемый:
  • 20–150 пикселей по стороне: значок, надпись на кнопке, кусок рамки;
  • только то, что не меняется: без цифр счётчиков, таймеров, анимации;
  • без лишнего фона по краям, особенно если фон за кнопкой меняется;
  • кнопку — в обычном виде, без подсветки от наведения мыши
    (уведите курсор в сторону перед выделением);
  • без курсора мыши внутри области.
Большой образец (пол-экрана) ищется дольше и чаще не совпадает целиком.

ЕСЛИ КАРТИНКА НЕ НАХОДИТСЯ
--------------------------
1. Окно стало другого размера, сменилось разрешение или масштаб Windows —
   добавьте scale:
       click_image("старт", scale: "auto")      // от 0.5 до 2 размеров
       click_image("старт", scale: 0.8..1.3)    // свой диапазон — быстрее
   Узнать найденный масштаб: log(find_image("старт", scale: "auto"))
   — в ответе будет scale, потом его можно указать числом: scale: 1.25.
2. Цвет чуть отличается (подсветка, прозрачность, ночной режим) —
   увеличьте допуск: tolerance: 40 (по умолчанию 20; 0 — точь-в-точь).
3. Кнопка мигает или подсвечивается — вырежьте её заново в обычном виде.
4. Включите тестовый режим (без кликов) и посмотрите лог: там видно,
   нашлась ли картинка и куда скрипт нажал бы.

СКОРОСТЬ
--------
Поиск по всему экрану без scale — сотые доли секунды. С scale — обычно
0,3–1 с, для очень маленькой картинки до 3 с. Ускорить можно областью
поиска — четыре числа после имени (x, y, ширина, высота, можно в %):
    click_image("старт", 0, 70%, 100%, 30%)   // только нижняя треть экрана
и узким диапазоном scale вместо "auto".

ЧТЕНИЕ ТЕКСТА
-------------
Область задаётся так же: x, y, ширина, высота.
    log(read_text(100, 200, 600, 300))              // весь текст области
    if (text_in(820, 400, 300, 60, "Готово")) { ... } // есть ли там слово
    wait_text(820, 400, 300, 60, "Готово", timeout: 2m)
    золото = read_number(1500, 40, 120, 30)         // число или null

Два способа распознавания (выбираются в разделе «Картинки и текст»):
  Точное (PaddleOCR)   — по умолчанию. Около секунды, но хорошо читает
                         мелкий, цветной и игровой текст, надписи на картинках.
  Быстрое (Windows)    — доли секунды, только для чёткого обычного текста
                         (окна программ, документы).
Для одной команды способ можно указать прямо в скрипте:
    read_text(100, 200, 600, 300, engine: "windows")
    read_text(100, 200, 600, 300, engine: "paddle")

СОВЕТЫ ДЛЯ ТЕКСТА
-----------------
  • Выделяйте плотно — только строку с нужным текстом, без значков рядом.
  • Распознавание не бывает идеальным: ищите слово целиком или его часть
    через text_in / wait_text, а не сравнивайте read_text(...) == "...".
    Сравнение там нестрогое: регистр, лишние пробелы и похожие русские и
    латинские буквы (о–o, с–c, р–p) не важны.
  • Числа читайте через read_number — он сам выбросит лишние символы.
  • Перед тем как писать скрипт, проверьте область в разделе «Картинки и
    текст»: если там текст читается правильно, в скрипте будет так же.

ПРИМЕРЫ ЦЕЛИКОМ
---------------
Дождаться загрузки и нажать «Играть»:
    if (!click_image("играть", timeout: 2m)) {
        log("кнопка «Играть» так и не появилась")
        exit()
    }

Собирать награду, пока золота меньше 1000:
    золото = read_number(1500, 40, 120, 30)
    while (золото != null && золото < 1000) {
        click_image("собрать", timeout: 30s)
        wait(2s)
        золото = read_number(1500, 40, 120, 30)
    }

Закрыть всплывающее окно, если оно появилось:
    click_image("крестик")      // нет окна — ничего не случится

ИНОГДА ПРОЩЕ ЦВЕТ
-----------------
Если важен один признак — индикатор стал зелёным, полоска заполнилась, —
быстрее проверить цвет точки (F6 вставит координаты и цвет под курсором):
    wait_pixel(960, 540, "#00FF00", timeout: 1m)
    if (pixel_is(100, 200, "#FF0000")) { ... }
''';
