const String beginnerGuide = r'''
ДЛЯ НОВИЧКОВ: ПЕРВЫЕ 5 МИНУТ
============================

ЧТО ЭТО
-------
SmartClicker выполняет за вас действия мышью и клавиатурой по сценарию
(скрипту). Скрипт — обычный текст: одна строка = одно действие.

    click(50%, 50%)     // кликнуть в центр экрана
    wait(1s)            // подождать секунду
    type("Привет")      // напечатать текст

САМЫЙ БЫСТРЫЙ СПОСОБ — ЗАПИСЬ
-----------------------------
1. Создайте скрипт (значок листа с плюсом слева).
2. Нажмите «Запись» (или F9). Пойдёт отсчёт — переключитесь в нужную программу.
3. Сделайте действия мышью и клавиатурой.
4. Нажмите F9 ещё раз. В скрипте появится готовый код.
5. Нажмите «Запуск» — программа повторит ваши действия.

ГОТОВЫЕ ШАБЛОНЫ
---------------
Значок листа с плюсом открывает окно «Новый скрипт» со списком шаблонов:
автокликер, нажимать клавишу через случайные паузы, дождаться кнопки и
нажать, нажимать кнопку каждый раз, когда появится, собирать награду каждые
N минут, кликать, пока видна картинка, дождаться надписи, ждать цвет точки,
фармить, пока число меньше N, повторить действия N раз. Заполните поля
(точку, картинку, интервал) — справа сразу виден готовый код и результат
его проверки. После создания код можно менять как угодно.

РЕЖИМЫ ЗАПИСИ (переключатель справа от кнопки «Запись»)
-------------------------------------------------------
Только клики и клавиши    короткий, понятный скрипт. Движение мыши не пишется.
Клики + остановки курсора ещё и места, где курсор задержался (по умолчанию
                          дольше 0.5 с) — нужно, когда вы наводите мышь, чтобы
                          раскрылось меню или появилась подсказка.
Полная траектория         весь путь курсора точка за точкой (команды
                          mouse_path). Повторяет движения в точности, но скрипт
                          получается длинным и его трудно править руками.
Привязывать к окнам       запись запоминает, В КАКОМ ОКНЕ был клик: в скрипт
                          вставляется focus_window("окно") и use_window("окно"),
                          координаты считаются от окна. Клики по панели задач
                          для переключения окон заменяются на focus_window.
                          Скрипт попадает, даже если окно потом стоит в другом
                          месте. Совет: включайте почти всегда.

ГЛАВНЫЕ КЛАВИШИ (меняются в настройках, работают в любой программе)
-------------------------------------------------------------------
F12   аварийная остановка — запомните её первой
F8    пауза / продолжить
F9    начать / остановить запись
F6    вставить в скрипт точку под курсором (координаты и цвет)

БЫСТРЫЕ НАСТРОЙКИ
-----------------
Серая надпись справа от кнопки «Запись» (например «только клики ▾») открывает
окно с самыми нужными переключателями: что записывать от мыши, привязка к
окнам, текст буквами или клавишами, формат координат (проценты/пиксели),
тест без кликов, показ места клика. Всё то же есть на вкладке «Настройки».

ТЕКСТ ИЛИ КЛАВИШИ?
------------------
При записи набранный текст по умолчанию сохраняется буквами: type("привет").
Это надёжно для полей ввода и не зависит от раскладки. Для игр и программ,
где важны именно нажатия (WASD, пробел), выключите в быстрых настройках
«Набранный текст как type» — тогда запишется key("w"), key("space").

ОТЛАДКА: ПОЧЕМУ СКРИПТ ДЕЛАЕТ НЕ ТО
-----------------------------------
• «Показывать место клика» (быстрые настройки): перед каждым кликом на экране
  на мгновение появляется красное кольцо — видно, куда целится скрипт.
• Пошаговый запуск: меню ⋮ над редактором → «Запустить пошагово». Скрипт
  останавливается перед каждой строкой (она подсвечена), кнопка «Шаг» выполняет
  её. «Продолжить» — дальше без остановок. Можно и обычный запуск поставить
  на паузу (F8) и идти дальше кнопкой «Шаг».
• «Тест без кликов» вместе с «Показывать место клика»: кольца показываются,
  а сами клики не выполняются.

ДЕЙСТВИЯ СО СКРИПТАМИ И ПАПКАМИ
-------------------------------
Правая кнопка мыши по скрипту или папке в списке: открыть, переименовать,
переместить в папку, создать копию, удалить. В именах можно использовать
буквы, цифры, пробел и знаки _ - . ( ).
Ctrl+Z — отменить правку, Ctrl+Y — вернуть, Ctrl+S — сохранить.

СВОЯ КЛАВИША ДЛЯ СКРИПТА
------------------------
Кнопка с клавиатурой над редактором назначает открытому скрипту клавишу или
сочетание. Нажатие запускает скрипт из любой программы сразу, без отсчёта.
Назначенная клавиша показана в списке скриптов в квадратных скобках.

АВТОЗАПУСК: ПО РАСПИСАНИЮ И ПО ПРОГРАММЕ
---------------------------------------
Раздел «Автозапуск», вкладка «По расписанию»: запуск скрипта каждый день в
заданное время или каждые N минут, пока SmartClicker открыт.

Вкладка «По программе» привязывает скрипт к программе:
  • «Когда программа запускается» — скрипт стартует, как только появится
    окно программы (например, вы открыли игру);
  • «Когда её окно становится активным» — скрипт стартует, когда вы
    переключились в это окно.
А когда программа закрылась или вы ушли в другое окно, скрипт можно
остановить, поставить на паузу (продолжится, когда окно снова активно) или
оставить работать. Программу проще всего выбрать стрелкой из списка
открытых окон; подходит и имя процесса (game.exe), и часть заголовка.
Программа, которая уже была открыта при запуске SmartClicker, не считается
«только что запущенной» — перезапустите её.

КАК УЗНАТЬ КООРДИНАТЫ
---------------------
Наведите курсор на нужное место в любой программе и нажмите F6 — в открытый
скрипт вставится click(...) с координатами. Вкладка «Инструменты» показывает
координаты и цвет под курсором в реальном времени.

Кнопка «Взять координаты кликом» там же: нажмите её и кликните в нужное
место — координаты скопируются в буфер обмена (Ctrl+V вставит их куда угодно).

Координаты бывают двух видов:
    click(960, 540)     // пиксели
    click(50%, 50%)     // проценты — работают на любом разрешении экрана

ЧИТАТЬ ТЕКСТ И ИСКАТЬ КАРТИНКИ
-----------------------------
Скрипт может находить кнопки по их виду и читать текст и числа с экрана —
это надёжнее координат. Подробно, с примерами и советами — в разделе
справки «Картинки и текст». Коротко:
    click_image("старт", timeout: 10s)        // дождаться кнопки и нажать
    if (text_in(820, 400, 300, 60, "Готово")) { click(960, 620) }
Вырезать кнопку: «Инструменты» → «Выделить область», два нажатия Ctrl.

СВОИ ЗАМЕТКИ
------------
Вкладка справки «Мои заметки»: список своих записей — что делает какой скрипт,
какие у вас есть функции («модули»), важные координаты. Это обычные файлы .md:
их можно импортировать и выгружать. Заметки добавляются в «Промпт для ИИ».
Строка поиска в справке открывается значком лупы или Ctrl+F и закрывается крестиком.

БЕЗОПАСНАЯ ПРОВЕРКА
-------------------
Включите «Тест без кликов» и запустите скрипт: действия не выполняются, а
только пишутся в лог. Так удобно проверять логику.

Перед каждым запуском скрипт проверяется на ошибки, которые видны без
запуска: опечатка в команде (clik вместо click — подскажет правильное имя),
переменная, которая нигде не задаётся, картинка или скрипт, которых нет,
бесконечный цикл без wait(). Найдена ошибка — скрипт не запускается, строка
подсвечивается, а в логе написано, что не так. Если вы уверены, что всё
верно, нажмите «Запуск» ещё раз — запустится как есть. Проверить без
запуска: меню ⋮ → «Проверить скрипт на ошибки». Выключить проверку:
Настройки → Запуск.

ПОВТОРЕНИЯ
----------
    repeat (10) {            // повторить 10 раз
        click(50%, 50%)
        wait(1s)
    }

    repeat {                 // бесконечно, до F12
        click(50%, 50%)
        wait(800..1200)      // случайная пауза от 0.8 до 1.2 секунды
    }

УСЛОВИЯ
-------
    if (pixel_is(50%, 50%, "#FF0000")) {     // если точка красная
        click(50%, 50%)
    } else {
        log("кнопки пока нет")
    }

РАБОТА С ОДНИМ ОКНОМ (самый надёжный способ)
--------------------------------------------
    focus_window("Game")                         // вывести окно вперёд
    set_window_bounds("Game", 0, 0, 1280, 720)   // всегда одно место и размер
    use_window("Game")                           // координаты — от окна
    require_window("Game")                       // не кликать мимо окна

    click(50%, 80%)

Важно: эти настройки действуют до конца скрипта. Вернуть работу со всем
экраном: use_screen() и require_window(null). Подробнее — «Частые ошибки».

То же, но только для части скрипта — блок with_window:

    with_window("Game") {
        click(50%, 80%)      // от окна Game, клик только в него
    }
    click(10, 10)            // после блока — снова от экрана

ПАПКИ И СОХРАНЕНИЕ
------------------
Скрипты можно раскладывать по папкам (значок папки с плюсом), папки можно
вкладывать друг в друга. Перенести скрипт: «Переименовать» → «Папка/Имя».
Точка ● рядом с именем — есть несохранённые изменения (Ctrl+S — сохранить).
Перенести можно и мышью: перетащите скрипт на папку (на пустое место — в корень).
Папку «Примеры» можно вернуть к исходному виду: меню ⋮ → «Восстановить примеры».

УДОБСТВА РЕДАКТОРА
------------------
  • Подсказки: наберите две буквы — появится список команд. Tab или Enter —
    вставить, Esc — закрыть. Внутри скобок видно, какие у команды параметры.
  • Наведите мышь на команду или параметр (timeout:, tolerance:, offset:) —
    появится пояснение. И то и другое отключается в настройках, блок «Редактор».
  • Ctrl+F — поиск, Ctrl+H — замена, Enter / Shift+Enter — следующее /
    предыдущее совпадение. В справке поиск всегда открыт вверху справа.
  • Ctrl+Z / Ctrl+Y — отменить / вернуть, Ctrl+S — сохранить.

МИНИ-ПАНЕЛЬ ПОВЕРХ ВСЕХ ОКОН
----------------------------
Кнопка внизу левой колонки сворачивает программу в маленькую панель: координаты
и цвет под курсором, запуск, пауза, стоп, запись. Панель не забирает фокус у
программы, в которой вы работаете, поэтому запуск с неё идёт без отсчёта.
Перетаскивается за любое свободное место. Скрипт «видит» панель как часть
экрана — не ставьте её туда, где он кликает или проверяет цвет.

ДОЛЖНА ЛИ ПРОГРАММА БЫТЬ ЗАПУЩЕНА
---------------------------------
Да. Скрипты, горячие клавиши и расписание работают, только пока SmartClicker
открыт (можно свернуть его или превратить в мини-панель). Закрыли окно —
скрипт остановился.

НЕСКОЛЬКО СКРИПТОВ ВМЕСТЕ («МОДУЛИ»)
------------------------------------
Общие функции можно держать в отдельном скрипте и подключать:

    run_script("Общее/Мои функции")   // выполнит тот скрипт
    собрать_награду()                 // его функции теперь доступны здесь

ЖДАТЬ ВРЕМЯ И ПРОВЕРЯТЬ ЧТО-ТО РАЗ В N МИНУТ
--------------------------------------------
    wait(10m)                  // просто подождать 10 минут
    wait_until("20:00")        // ждать до 20:00 (время сверяется каждую секунду,
                               // это ничего не нагружает; пауза и стоп работают)

    // раз в 10 минут проверять условие и работать только до 20:00
    while (time() < "20:00:00") {
        if (pixel_is(50%, 50%, "#22CC44", tolerance: 25)) {
            click(50%, 50%)
        }
        wait(10m)
    }

ПОПРОСИТЬ НЕЙРОСЕТЬ НАПИСАТЬ СКРИПТ
-----------------------------------
Нажмите «Скопировать промпт для ИИ» вверху этой страницы, вставьте в чат с
ChatGPT / Claude / Gemini и допишите, что должен делать скрипт. Ответ вставьте
в редактор.

ЕСЛИ ЧТО-ТО ПОШЛО НЕ ТАК
------------------------
Смотрите лог внизу: там видно каждое действие и строку, где случилась ошибка
(она подсвечивается красным в редакторе). Логи всех запусков сохраняются в
файлы — вкладка «История».

При ошибке программа сохраняет ОТЧЁТ одним файлом: скрипт, лог, настройки и
снимок экрана в момент ошибки. В «Истории» у такого запуска есть кнопка с
роботом — она копирует отчёт вместе с промптом: вставьте в чат с
нейросетью, и она найдёт причину. Кнопка с жуком в шапке лога сохраняет
отчёт вручную.

ЧТО ВНУТРИ СКРИПТА: ПЕРЕМЕННЫЕ И ТОЧКИ ОСТАНОВА
-----------------------------------------------
Под редактором две вкладки: «Лог» и «Переменные». Во вкладке
«Переменные» видны значения всех переменных скрипта: во время работы они
обновляются несколько раз в секунду (изменившиеся — жёлтым), после запуска
остаются последние, а при ошибке — те, что были в момент ошибки (они же
попадают в отчёт). Переменные внутри функции подписаны её именем.

Точка останова — щёлкните по номеру строки слева в редакторе, появится
красная точка. Скрипт остановится ПЕРЕД этой строкой: посмотрите значения,
затем «Продолжить» (дальше до следующей точки) или «Шаг» (одна строка).
Повторный щелчок убирает точку; убрать все — меню ⋮. Точки можно ставить и
во время работы. Точки внутри цикла срабатывают на каждом повторе.

ДОЛГАЯ РАБОТА БЕЗ ПРИСМОТРА
---------------------------
Настройки → Запуск → «Перезапускать после ошибки, раз подряд». Если скрипт
упал (например, игра долго грузилась и кнопка не нашлась), он запустится
заново через заданную паузу. Каждый сбой сохраняет отчёт. Число — сколько
раз подряд можно перезапустить; 0 — выключено (так по умолчанию). Стоп или
успешное завершение сбрасывают счёт.
